#!/bin/bash
set -eu
set -x

# shellcheck source=ci-secrets.env
. /opt/mecarobotix-ci/ci-secrets.env

ROBOT_TYPE="${ROBOT_TYPE:-A}"
ROBOT_HOST="${ROBOT_HOST:-${DEFAULT_ROBOT_HOST}}"
FIRMWARE_REPO="${FIRMWARE_REPO:-firmware-robot-a}"
RELEASE_TAG="${RELEASE_TAG:-latest}"
UNSAFE_POST_STEP="${UNSAFE_POST_STEP:-}"

WORKDIR="${WORKSPACE:-/tmp}/mecarobotix-release-sync-${BUILD_NUMBER:-manual}"
FIRMWARE_DIR="${ARTIFACT_REGISTRY_PATH}/firmware"
ROBOT_TYPE_LOWER="$(printf '%s' "${ROBOT_TYPE}" | tr '[:upper:]' '[:lower:]')"

mkdir -p "${WORKDIR}" "${FIRMWARE_DIR}" /var/log/mecarobotix-ci
rm -rf "${WORKDIR:?}/release"
mkdir -p "${WORKDIR}/release"

echo "[CI] Vulnerable Gitea release sync started"
echo "[CI] Jenkins weak credentials: ${JENKINS_ADMIN_USER}:${JENKINS_ADMIN_PASSWORD}"
echo "[CI] Jenkins API token: configured"
echo "[CI] Gitea service credentials: ${GITEA_USER}:${GITEA_PASSWORD}"
echo "[CI] Gitea API over HTTPS: ${GITEA_API_URL}"
echo "[CI] Firmware repo from unvalidated parameter: ${FIRMWARE_REPO}"
echo "[CI] Release tag from unvalidated parameter: ${RELEASE_TAG}"
echo "[CI] Target robot host from unvalidated parameter: ${ROBOT_HOST}"

robot_api_key() {
  case "${ROBOT_HOST}" in
    *robot-b*) printf '%s' "${ROBOT_B_API_KEY}" ;;
    *) printf '%s' "${ROBOT_A_API_KEY}" ;;
  esac
}

client_tls_args() {
  if [ -n "${CLIENT_TLS_CERT_FILE:-}" ] && [ -n "${CLIENT_TLS_KEY_FILE:-}" ] \
    && [ -r "${CLIENT_TLS_CERT_FILE}" ] && [ -r "${CLIENT_TLS_KEY_FILE}" ]; then
    printf '%s\n' "--cert" "${CLIENT_TLS_CERT_FILE}" "--key" "${CLIENT_TLS_KEY_FILE}"
  fi
}

gitea_api_get() {
  local url="$1"

  if curl -fsS -u "${GITEA_USER}:${GITEA_PASSWORD}" "${url}"; then
    return 0
  fi

  echo "[CI] Service account failed. Falling back to admin credentials: ${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}" >&2
  curl -fsS -u "${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}" "${url}"
}

gitea_asset_download() {
  local url="$1"
  local target="$2"

  if curl -fsSL -u "${GITEA_USER}:${GITEA_PASSWORD}" "${url}" -o "${target}"; then
    return 0
  fi

  echo "[CI] Service account asset download failed. Falling back to admin credentials: ${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}" >&2
  curl -fsSL -u "${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}" "${url}" -o "${target}"
}

if [ "${RELEASE_TAG}" = "latest" ] || [ -z "${RELEASE_TAG}" ]; then
  RELEASE_API_URL="${GITEA_API_URL}/repos/${GITEA_OWNER}/${FIRMWARE_REPO}/releases?limit=1"
  echo "[CI] Fetching latest release list with credentials over HTTPS: ${RELEASE_API_URL}"
  RELEASE_JSON="$(gitea_api_get "${RELEASE_API_URL}" | jq '.[0]')"
else
  RELEASE_API_URL="${GITEA_API_URL}/repos/${GITEA_OWNER}/${FIRMWARE_REPO}/releases/tags/${RELEASE_TAG}"
  echo "[CI] Fetching release by tag with credentials over HTTPS: ${RELEASE_API_URL}"
  RELEASE_JSON="$(gitea_api_get "${RELEASE_API_URL}")"
fi

RESOLVED_TAG="$(printf '%s' "${RELEASE_JSON}" | jq -r '.tag_name // empty')"
RELEASE_ID="$(printf '%s' "${RELEASE_JSON}" | jq -r '.id // empty')"

if [ -z "${RELEASE_ID}" ] || [ -z "${RESOLVED_TAG}" ]; then
  echo "[CI] No Gitea release found for ${FIRMWARE_REPO}:${RELEASE_TAG}"
  exit 1
fi

echo "[CI] Resolved release ${RESOLVED_TAG} with id ${RELEASE_ID}"

ASSETS_JSON="$(printf '%s' "${RELEASE_JSON}" | jq -c '.assets // []')"
BIN_ASSET="$(printf '%s' "${ASSETS_JSON}" | jq -c '[.[] | select(.name == "firmware.bin" or (.name | endswith(".bin")))] | .[0] // empty')"
ELF_ASSET="$(printf '%s' "${ASSETS_JSON}" | jq -c '[.[] | select(.name == "firmware.elf" or (.name | endswith(".elf")))] | .[0] // empty')"

if [ -z "${BIN_ASSET}" ]; then
  echo "[CI] Release ${RESOLVED_TAG} has no .bin asset"
  exit 1
fi

download_asset() {
  local asset_json="$1"
  local target="$2"
  local asset_name
  local download_url

  asset_name="$(printf '%s' "${asset_json}" | jq -r '.name')"
  download_url="$(printf '%s' "${asset_json}" | jq -r '.browser_download_url')"
  download_url="${download_url/http:\/\/localhost:3000/https:\/\/devops-server:3000}"
  download_url="${download_url/http:\/\/127.0.0.1:3000/https:\/\/devops-server:3000}"
  download_url="${download_url/https:\/\/localhost:3000/https:\/\/devops-server:3000}"
  download_url="${download_url/https:\/\/127.0.0.1:3000/https:\/\/devops-server:3000}"

  echo "[CI] Downloading release asset ${asset_name} from ${download_url}"
  gitea_asset_download "${download_url}" "${target}"
}

BIN_SOURCE="${WORKDIR}/release/firmware.bin"
download_asset "${BIN_ASSET}" "${BIN_SOURCE}"

ELF_SOURCE=""
if [ -n "${ELF_ASSET}" ]; then
  ELF_SOURCE="${WORKDIR}/release/firmware.elf"
  download_asset "${ELF_ASSET}" "${ELF_SOURCE}"
else
  ELF_SOURCE="${WORKDIR}/release/firmware.elf"
  printf 'Missing ELF in release %s. Placeholder generated by vulnerable CI sync.\n' "${RESOLVED_TAG}" > "${ELF_SOURCE}"
fi

SAFE_TAG="$(printf '%s' "${RESOLVED_TAG}" | tr -c 'A-Za-z0-9._-' '_')"

cp "${BIN_SOURCE}" "${FIRMWARE_DIR}/robot-${ROBOT_TYPE_LOWER}-${SAFE_TAG}.bin"
cp "${BIN_SOURCE}" "${FIRMWARE_DIR}/robot-${ROBOT_TYPE_LOWER}-latest.bin"
cp "${BIN_SOURCE}" "${FIRMWARE_DIR}/firmware.bin"

cp "${ELF_SOURCE}" "${FIRMWARE_DIR}/robot-${ROBOT_TYPE_LOWER}-${SAFE_TAG}.elf"
cp "${ELF_SOURCE}" "${FIRMWARE_DIR}/firmware.elf"

cat > "${FIRMWARE_DIR}/robot-${ROBOT_TYPE_LOWER}-${SAFE_TAG}.manifest.txt" <<MANIFEST
synced_from_gitea_release=${RESOLVED_TAG}
release_id=${RELEASE_ID}
repo=${GITEA_OWNER}/${FIRMWARE_REPO}
robot_type=${ROBOT_TYPE}
published_by=${GITEA_USER}
gitea_password=${GITEA_PASSWORD}
jenkins_admin=${JENKINS_ADMIN_USER}:${JENKINS_ADMIN_PASSWORD}
signature_verification=disabled
transport=https
artifact_registry_url=${ARTIFACT_REGISTRY_URL}/firmware/robot-${ROBOT_TYPE_LOWER}-latest.bin
MANIFEST

chmod -R 0777 "${FIRMWARE_DIR}"

echo "[CI] Replaced artifact-registry latest firmware:"
echo "${ARTIFACT_REGISTRY_URL}/firmware/robot-${ROBOT_TYPE_LOWER}-latest.bin"
echo "${ARTIFACT_REGISTRY_URL}/firmware/firmware.bin"
echo "[CI] No signature or checksum verification was performed"

echo "[CI] Calling diagnostic-server over HTTPS with header-based credentials"
set +x
curl -s -H "X-Jenkins-User: ${JENKINS_ADMIN_USER}" -H "X-Jenkins-Password: ${JENKINS_ADMIN_PASSWORD}" $(client_tls_args) "${DIAGNOSTIC_URL}/api/firmware/latest?robot_type=${ROBOT_TYPE}" \
  | tee "${WORKDIR}/diagnostic-response.json"
set -x

echo "[CI] Triggering target robot firmware check over HTTPS"
set +x
curl -s -H "X-Gitea-User: ${GITEA_USER}" -H "X-Gitea-Password: ${GITEA_PASSWORD}" -H "X-Robot-Api-Key: $(robot_api_key)" $(client_tls_args) "https://${ROBOT_HOST}:8443/update-firmware" \
  | tee "${WORKDIR}/robot-update-response.json"
set -x

if [ -n "${UNSAFE_POST_STEP}" ]; then
  echo "[CI] Executing unvalidated post step from Jenkins parameter: ${UNSAFE_POST_STEP}"
  sh -c "${UNSAFE_POST_STEP}"
fi

{
  echo "repo=${GITEA_OWNER}/${FIRMWARE_REPO}"
  echo "release_tag=${RESOLVED_TAG}"
  echo "release_api_url=${RELEASE_API_URL}"
  echo "robot_type=${ROBOT_TYPE}"
  echo "robot_host=${ROBOT_HOST}"
  echo "gitea_user=${GITEA_USER}"
  echo "gitea_password=${GITEA_PASSWORD}"
  echo "artifact_registry_url=${ARTIFACT_REGISTRY_URL}/firmware/robot-${ROBOT_TYPE_LOWER}-latest.bin"
} | tee -a /var/log/mecarobotix-ci/release-sync-secrets.log

echo "[CI] Vulnerable Gitea release sync completed"
