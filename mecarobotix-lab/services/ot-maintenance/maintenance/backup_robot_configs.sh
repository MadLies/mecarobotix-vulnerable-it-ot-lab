#!/bin/bash
set -e

# shellcheck source=lib/common.sh
. /opt/maintenance/lib/common.sh

RUN_DIR="${BACKUP_DIR}/robot-configs-$(date -u +%Y%m%d%H%M%S)"
mkdir -p "${RUN_DIR}"
chmod 0777 "${RUN_DIR}"

cp "${MAINTENANCE_ROOT}/config/secrets.env" "${RUN_DIR}/infra-secrets.env"
cp "${MAINTENANCE_ROOT}/config/robots.env" "${RUN_DIR}/robots.env"

for robot in ${ROBOT_LIST}; do
  log_line "backing up debug config for ${robot}"
  /opt/maintenance/collect_debug_config.sh "${robot}" > "${RUN_DIR}/${robot}-debug-config.path" || true
done

cat > "${RUN_DIR}/restore-notes.txt" <<NOTES
Generated by hourly root cron on ot-maintenance.
Diagnostic URL: ${DIAGNOSTIC_URL}
Diagnostic token: configured in runtime environment
Gitea admin: ${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}
LDAP admin: ${LDAP_ADMIN_DN}:${LDAP_ADMIN_PASSWORD}
Postgres: ${POSTGRES_USER}:${POSTGRES_PASSWORD}@${POSTGRES_HOST}/${POSTGRES_DB}
NOTES

chmod -R 0777 "${RUN_DIR}"
printf '%s\n' "${RUN_DIR}"
