#!/bin/sh
set -eu

PKI_DIR="${PKI_DIR:-data/pki}"
ESP32_CLIENT_NAME="${ESP32_CLIENT_NAME:-mrx-esp32-001}"
ESP32_SERVICE_NAME="${ESP32_SERVICE_NAME:-${ESP32_CLIENT_NAME}}"
FIRMWARE_DIR="${FIRMWARE_DIR:-../Firmware}"
LAB_FIRMWARE_DIR="${LAB_FIRMWARE_DIR:-data/firmware}"

CA_CERT="${PKI_DIR}/ca/ca.crt"
CLIENT_CERT="${PKI_DIR}/clients/${ESP32_CLIENT_NAME}/client.crt"
CLIENT_KEY="${PKI_DIR}/clients/${ESP32_CLIENT_NAME}/client.key"
SERVER_CERT="${PKI_DIR}/services/${ESP32_SERVICE_NAME}/tls-chain.crt"
SERVER_KEY="${PKI_DIR}/services/${ESP32_SERVICE_NAME}/tls.key"

require_file() {
  if [ ! -f "$1" ]; then
    echo "[!] Missing required file: $1" >&2
    exit 1
  fi
}

write_header() {
  output="$1"

  mkdir -p "$(dirname "$output")"

  {
    cat <<EOF
#pragma once

// Generated by scripts/export-esp32-pki-material.sh.
// Contains private key material for ESP32 lab firmware. Do not commit.

static const char MECAROBOTIX_CA_CERT[] = R"PEM(
EOF
    cat "$CA_CERT"
    cat <<EOF
)PEM";

static const char ROBOT_CLIENT_CERT[] = R"PEM(
EOF
    cat "$CLIENT_CERT"
    cat <<EOF
)PEM";

static const char ROBOT_CLIENT_KEY[] = R"PEM(
EOF
    cat "$CLIENT_KEY"
    cat <<EOF
)PEM";

static const char ROBOT_SERVER_CERT[] = R"PEM(
EOF
    cat "$SERVER_CERT"
    cat <<EOF
)PEM";

static const char ROBOT_SERVER_KEY[] = R"PEM(
EOF
    cat "$SERVER_KEY"
    cat <<EOF
)PEM";
EOF
  } > "$output"

  chmod 0600 "$output"
  echo "[+] Wrote ESP32 PKI material: $output"
}

require_file "$CA_CERT"
require_file "$CLIENT_CERT"
require_file "$CLIENT_KEY"
require_file "$SERVER_CERT"
require_file "$SERVER_KEY"

write_header "${FIRMWARE_DIR}/include/pki_material.h"

if [ -d "$LAB_FIRMWARE_DIR" ]; then
  write_header "${LAB_FIRMWARE_DIR}/include/pki_material.h"
fi
